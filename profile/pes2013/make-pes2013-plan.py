#!/usr/bin/env python3
"""Writes PES 2013's install plan for the launcher (launcher/assets/plans/PES2013.json).

  profile/pes2013/make-pes2013-plan.py [OUT]

The plan downloads nothing and adds nothing but our dxvk.conf: the user's folder, mods and all,
is installed as it is. Our own files go in as texts; settings.dat is written from
settings_dat.py's layout for the page's picture size.
"""
import importlib.util, json, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "launcher/assets/plans/PES2013.json"
SAVE = "Documents/KONAMI/Pro Evolution Soccer 2013"
KEY = "Software\\Wow6432Node\\KONAMI\\PES2013"  # the 32-bit game's HKLM\Software\KONAMI\PES2013

spec = importlib.util.spec_from_file_location("settings_dat", HERE / "settings_dat.py")
settings_dat = importlib.util.module_from_spec(spec)
spec.loader.exec_module(settings_dat)


def text(name):
    return (HERE / name).read_text()


def plan():
    return {
        "schema": 1,
        "game": "PES2013",
        "title": "PES 2013",
        "release": "",
        "prefix": "futbol13",
        "_about": "Generated by profile/pes2013/make-pes2013-plan.py. Nothing is downloaded.",
        "sources": {},
        "strip": [],
        "game_files": [],
        "system_files": [],
        "patches": [],
        "ini": [],
        "texts": [{"to": "dxvk.conf", "body": text("dxvk.conf")}],
        "expect": {},
        # What the game's own installer leaves in the registry: pes2013.exe reads installdir at
        # start, looks for img/dt00_*.img and dt05_*.img there, then reads "code", the player's
        # CD key; with either missing it says "Pro Evolution Soccer 2013 has not been
        # installed". The key is not in the game folder, so the plan can't write it.
        "registry": {"machine": [
            {"key": KEY, "name": "installdir", "string": "C:\\Games\\PES2013\\"},
            {"key": KEY, "name": "version", "string": "1.00.0000"},
        ], "user": []},
        "user_files": [],
        # The player's save folder from /data/futbol13/saves/PES2013/save (options, edited
        # squads, the EDIT file a squad update gives): copied where the game has none yet.
        "user_seeds": [{"from": "save", "file": SAVE + "/save"}],
        # settings.exe's file, written by us for the page's resolution.
        "user_binaries": [{"file": SAVE + "/settings.dat", "bytes": settings_dat.TEMPLATE_HEX,
                           "fields": settings_dat.FIELDS, "checksum": settings_dat.CHECKSUM}],
        "profile": {
            "id": "pb-futbol13",
            "name": "FUTBOL13",
            "executable": "C:\\Games\\PES2013\\pes2013.exe",
            "working_directory": "C:\\Games\\PES2013",
            "dll_overrides": "d3d9,dxgi=n;dinput8=n,b",
            "width": 3840,
            "height": 2160,
            "runtime": {"fast_clock": "true", "shared_input": "true", "thread_scheduling": "true"},
            "after": "futbol13.profile",
        },
        "pending": [],
        "options": [],
        "upgrades": [],
    }


if __name__ == "__main__":
    out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(plan(), indent=1) + "\n")
