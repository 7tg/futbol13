# Little-endian 32-bit fields written over the template; everything else is already right in it.
FIELDS = [
    {"at": WIDTH_AT, "u32": "{width}"},
    {"at": HEIGHT_AT, "u32": "{height}"},
]
CHECKSUM = {"kind": "crc16-xmodem-not", "at": CHECKSUM_AT}


def crc16_not(data):
    """The checksum of data, whose bytes at CHECKSUM_AT and CHECKSUM_AT + 1 must already be 0."""
    c = 0
    for b in data:
        c ^= b << 8
        for _ in range(8):
            c = ((c << 1) ^ 0x1021) & 0xFFFF if c & 0x8000 else (c << 1) & 0xFFFF
    return (~c) & 0xFFFF


def render(width, height):
    """The file for a picture size, as the launcher writes it."""
    out = bytearray(bytes.fromhex(TEMPLATE_HEX))
    for field in FIELDS:
        value = {"{width}": width, "{height}": height}.get(field["u32"], field["u32"])
        struct.pack_into("<I", out, field["at"], value)
    struct.pack_into("<H", out, CHECKSUM_AT, 0)
    struct.pack_into("<H", out, CHECKSUM_AT, crc16_not(out))
    return bytes(out)
